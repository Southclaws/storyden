func WithInternal(ctx context.Context) context.Context {
	return context.WithValue(ctx, sessionContextKey, sessionContext{
		account:        opt.NewEmpty[account.Account](),
		permissions:    rbac.NewList(),
		securityScheme: "",
		sessionToken:   opt.NewEmpty[string](),
	})
}

func Authorise(ctx context.Context, fn func() error, perms ...rbac.Permission) error {
	value := ctx.Value(sessionContextKey)
	if value == nil {
		panic("request context does not contain a session context value, this is an internal bug")
	}

	sc, ok := value.(sessionContext)
	if !ok {
		return fault.Wrap(ErrMalformedContextValue, fctx.With(ctx), ftag.With(ftag.Unauthenticated))
	}

	return sc.permissions.Authorise(ctx, fn, perms...)
}

func HasContext(ctx context.Context) bool {
	_, ok := ctx.Value(sessionContextKey).(sessionContext)
	return ok
}

func GetPermissions(ctx context.Context) (rbac.Permissions, error) {
	value := ctx.Value(sessionContextKey)
	if value == nil {
		panic("request context does not contain a session context value, this is an internal bug")
	}

	sc, ok := value.(sessionContext)
	if !ok {
		return rbac.Permissions{}, fault.Wrap(ErrMalformedContextValue, fctx.With(ctx), ftag.With(ftag.Unauthenticated))
	}

	return sc.permissions, nil
}

func GetOAuthScopes(ctx context.Context) ([]string, error) {
	value := ctx.Value(sessionContextKey)
	if value == nil {
		panic("request context does not contain a session context value, this is an internal bug")
	}

	sc, ok := value.(sessionContext)
	if !ok {
		return nil, fault.Wrap(ErrMalformedContextValue, fctx.With(ctx), ftag.With(ftag.Unauthenticated))
	}

	return append([]string{}, sc.oauthScopes...), nil
}

// GetAccountID pulls out an account ID associated with the call.
func GetAccountID(ctx context.Context) (account.AccountID, error) {
	value := ctx.Value(sessionContextKey)
	if value == nil {
		panic("request context does not contain a session context value, this is an internal bug")
	}

	sc, ok := value.(sessionContext)
	if !ok {
		return account.AccountID{}, fault.Wrap(ErrMalformedContextValue, fctx.With(ctx), ftag.With(ftag.Unauthenticated))
	}

	acc, ok := sc.account.Get()
	if !ok {
		return account.AccountID{}, fault.Wrap(ErrNoAccountInContext,
			fctx.With(ctx),
			ftag.With(ftag.Unauthenticated),
			fmsg.With("GetAccountID"),
		)
	}

	return acc.ID, nil
}

