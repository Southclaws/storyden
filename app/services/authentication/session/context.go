var (
	ErrNoAccountInContext    = errors.New("no account in context")
	ErrMalformedContextValue = errors.New("malformed context value: internal bug")
)

type contextKey struct{}

var sessionContextKey = contextKey{}

type sessionContext struct {
	account     opt.Optional[account.Account]
	permissions rbac.Permissions
	oauthScopes []string

	// NOTE: These are the security schemes defined in the OpenAPI spec under
	// `securitySchemes` - they aren't generated by the codegen so be careful.
	securityScheme string

	// sessionToken stores the session token for later revocation during logout.
	// This is only populated for browser sessions, not access keys.
	sessionToken opt.Optional[string]

	// accessKeyKind is only populated when securityScheme is "access_key", to
	// distinguish a member's personal key from a plugin/robot's bot key.
	accessKeyKind opt.Optional[access_key.AccessKeyKind]
}

func WithAccount(ctx context.Context, u account.Account, roles role.Roles) context.Context {
	return WithAccountPermissions(ctx, u, roles.Permissions())
}

func WithAccountPermissions(ctx context.Context, u account.Account, permissions rbac.Permissions) context.Context {
	return context.WithValue(ctx, sessionContextKey, sessionContext{
		account:        opt.New(u),
		permissions:    permissions,
		securityScheme: "browser",
		sessionToken:   opt.NewEmpty[string](),
	})
}

func WithAccountAndToken(ctx context.Context, u account.Account, roles role.Roles, token string) context.Context {
	return context.WithValue(ctx, sessionContextKey, sessionContext{
		account:        opt.New(u),
		permissions:    roles.Permissions(),
		securityScheme: "browser",
		sessionToken:   opt.New(token),
	})
}

func WithAccessKey(ctx context.Context, u account.Account, roles role.Roles) context.Context {
	return WithAccessKeyPermissions(ctx, u, roles.Permissions())
}

func WithAccessKeyPermissions(ctx context.Context, u account.Account, permissions rbac.Permissions) context.Context {
	return context.WithValue(ctx, sessionContextKey, sessionContext{
		account:        opt.New(u),
		permissions:    permissions,
		securityScheme: "access_key",
		sessionToken:   opt.NewEmpty[string](),
	})
}

// WithAccessKeyOfKind is identical to WithAccessKey but also records which
// kind of access key (personal or bot) authenticated the request, for
// operations that must be restricted to a member's own personal key.
func WithAccessKeyOfKind(ctx context.Context, u account.Account, roles role.Roles, kind access_key.AccessKeyKind) context.Context {
	ctx = WithAccessKey(ctx, u, roles)
	sc := ctx.Value(sessionContextKey).(sessionContext)
	sc.accessKeyKind = opt.New(kind)
	return context.WithValue(ctx, sessionContextKey, sc)
}

