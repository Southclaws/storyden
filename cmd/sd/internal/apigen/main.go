// Command apigen generates typed adapters for api<OperationID> handlers in
// opencli.yaml. OpenCLI itself remains responsible for the Cobra command tree.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"gopkg.in/yaml.v3"
)

type parameter struct {
	Name         string   `yaml:"name"`
	Ref          string   `yaml:"$ref"`
	Repeatable   bool     `yaml:"repeatable"`
	TrackChanged bool     `yaml:"trackChanged"`
	Type         string   `yaml:"type"`
	Choices      []string `yaml:"choices"`
	Variadic     bool     `yaml:"variadic"`
	SplitOnComma bool     `yaml:"splitOnComma"`
}
type command struct {
	Name      string      `yaml:"name"`
	ID        string      `yaml:"operationId"`
	Arguments []parameter `yaml:"arguments"`
	Flags     []parameter `yaml:"flags"`
	Commands  []command   `yaml:"commands"`
}

func main() {
	check := flag.Bool("check", false, "Check generated adapters without writing")
	flag.Parse()
	data, err := os.ReadFile("opencli.yaml")
	must(err)
	var spec struct {
		Commands   []command   `yaml:"commands"`
		Flags      []parameter `yaml:"flags"`
		Components struct {
			Flags     map[string]parameter `yaml:"flags"`
			Arguments map[string]parameter `yaml:"arguments"`
		} `yaml:"components"`
	}
	must(yaml.Unmarshal(data, &spec))
	must(resolveFlags(spec.Commands, spec.Components.Flags))
	must(resolveArguments(spec.Commands, spec.Components.Arguments))
	loader := openapi3.NewLoader()
	loader.IsExternalRefsAllowed = true
	api, err := loader.LoadFromFile("../../api/openapi.yaml")
	must(err)
	must(validateBindings(spec.Commands, api))
	data, err = generate(spec.Commands)
	must(err)
	writeGenerated("internal/apiexec/adapters.gen.go", data, *check)
	data, err = generateCompletions(spec.Commands, spec.Flags, api)
	must(err)
	writeGenerated("internal/completion/commands.gen.go", data, *check)
}

func writeGenerated(path string, data []byte, check bool) {
	if check {
		existing, err := os.ReadFile(path)
		must(err)
		if !bytes.Equal(existing, data) {
			panic(path + " is stale; run go generate ./cmd/sd")
		}
		return
	}
	must(os.WriteFile(path, data, 0644))
}

func generate(commands []command) ([]byte, error) {
	var b strings.Builder
	b.WriteString(`// Code generated by apigen from opencli.yaml. DO NOT EDIT.
package apiexec
import (
 "context"
 "net/url"

 "github.com/spf13/cobra"
 "go.uber.org/fx"
 "github.com/Southclaws/storyden/cmd/sd/internal/cligen"
)
func Build() fx.Option {
 return fx.Provide(
`)
	var walk func([]command)
	walk = func(commands []command) {
		for _, c := range commands {
			if strings.HasPrefix(c.ID, "api") {
				operation := strings.TrimPrefix(c.ID, "api")
				scope := exported(c.ID)
				fmt.Fprintf(&b, "func(e *Executor) cligen.%sHandler {\nreturn func(ctx context.Context, cmd *cobra.Command, streams cligen.IO, p cligen.%sParams) error {\n", scope, scope)
				b.WriteString("query := url.Values{}\n")
				for _, f := range c.Flags {
					if !isQuery(f.Name) {
						continue
					}
					name := strings.ReplaceAll(f.Name, "-", "_")
					field := exported(f.Name)
					if f.Repeatable {
						fmt.Fprintf(&b, "if p.%sSet { query[%q] = p.%s }\n", field, name, field)
					} else {
						fmt.Fprintf(&b, "if p.%sSet { query.Set(%q, p.%s) }\n", field, name, field)
					}
				}
				fmt.Fprintf(&b, "return e.Run(ctx, streams, Request{Operation: %q, Query: query, Output: string(p.Output), OutputFile: p.OutputFile, Timeout: p.Timeout, Path: map[string]string{", operation)
				for _, a := range c.Arguments {
					fmt.Fprintf(&b, "%q: p.%s,", strings.ToLower(a.Name), exported(a.Name))
				}
				b.WriteString("},")
				for _, f := range c.Flags {
					if f.Name == "data" || f.Name == "file" || f.Name == "content-type" {
						fmt.Fprintf(&b, "%s:p.%s,", exported(f.Name), exported(f.Name))
					}
				}
				b.WriteString("})\n}\n},\n")
			}
			walk(c.Commands)
		}
	}
	walk(commands)
	b.WriteString(")\n}\n")
	return format.Source([]byte(b.String()))
}

func exported(s string) string {
	var result strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' || r == ' ' }) {
		if part == strings.ToUpper(part) && len(part) > 1 {
			part = strings.ToLower(part)
		}
		result.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return result.String()
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}

func isQuery(name string) bool {
	switch name {
	case "output", "output-file", "timeout", "data", "file", "content-type":
		return false
	}
	return true
}
