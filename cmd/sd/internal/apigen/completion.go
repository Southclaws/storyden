package main

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

func resolveArguments(commands []command, components map[string]parameter) error {
	for i := range commands {
		for j, arg := range commands[i].Arguments {
			if arg.Ref == "" {
				continue
			}
			value, ok := components[strings.TrimPrefix(arg.Ref, "#/components/arguments/")]
			if !ok {
				return fmt.Errorf("unknown argument reference %q", arg.Ref)
			}
			commands[i].Arguments[j] = value
		}
		if err := resolveArguments(commands[i].Commands, components); err != nil {
			return err
		}
	}
	return nil
}

// generateCompletions keeps input names and finite choices tied to their contracts.
// Resource lookup policy lives in completion, independently of command layout.
func generateCompletions(commands []command, flags []parameter, api *openapi3.T) ([]byte, error) {
	operations := map[string]apiOperation{}
	for _, item := range api.Paths.Map() {
		for _, op := range item.Operations() {
			operations[op.OperationID] = apiOperation{op, append(append(openapi3.Parameters{}, item.Parameters...), op.Parameters...)}
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by apigen from opencli.yaml and api/openapi.yaml. DO NOT EDIT.\npackage completion\nfunc definitions() []command { return []command{\n")
	var walk func(command, string)
	walk = func(c command, path string) {
		op := operations[strings.TrimPrefix(c.ID, "api")]
		fmt.Fprintf(&b, "{Path:%q, Operation:%q, Arguments:[]input{", path, strings.TrimPrefix(c.ID, "api"))
		writeInputs(&b, c.Arguments, op, "path")
		b.WriteString("}, Flags:[]input{")
		writeInputs(&b, c.Flags, op, "query")
		b.WriteString("}},\n")
		for _, child := range c.Commands {
			walk(child, strings.TrimSpace(path+" "+child.Name))
		}
	}
	walk(command{Commands: commands, Flags: flags}, "")
	b.WriteString("}}\n")
	return format.Source([]byte(b.String()))
}

func writeInputs(b *strings.Builder, inputs []parameter, op apiOperation, location string) {
	for _, p := range inputs {
		choices := append([]string{}, p.Choices...)
		if len(choices) == 0 {
			for _, ref := range op.parameters {
				param := ref.Value
				if param.In == location && param.Name == strings.ToLower(strings.ReplaceAll(p.Name, "-", "_")) {
					choices = schemaChoices(param.Schema)
				}
			}
		}
		if p.Name == "content-type" && op.spec != nil && op.spec.RequestBody != nil {
			for mime := range op.spec.RequestBody.Value.Content {
				choices = append(choices, mime)
			}
			sort.Strings(choices)
		}
		fmt.Fprintf(b, "{Name:%q, Type:%q, Variadic:%t, SplitOnComma:%t, Choices:[]string{", p.Name, p.Type, p.Variadic, p.SplitOnComma)
		for _, choice := range choices {
			fmt.Fprintf(b, "%q,", choice)
		}
		b.WriteString("}},")
	}
}

func schemaChoices(ref *openapi3.SchemaRef) []string {
	if ref == nil || ref.Value == nil {
		return nil
	}
	s := ref.Value
	if s.Type.Is("array") {
		return schemaChoices(s.Items)
	}
	var values []string
	for _, v := range s.Enum {
		values = append(values, fmt.Sprint(v))
	}
	if len(values) == 0 && s.Type.Is("boolean") {
		return []string{"true", "false"}
	}
	for _, sub := range s.AllOf {
		values = append(values, schemaChoices(sub)...)
	}
	for _, sub := range s.OneOf {
		values = append(values, schemaChoices(sub)...)
	}
	for _, sub := range s.AnyOf {
		values = append(values, schemaChoices(sub)...)
	}
	return values
}
