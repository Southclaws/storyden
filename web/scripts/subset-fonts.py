"""Regenerate Inter's static Unicode subsets: uv run web/scripts/subset-fonts.py."""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

FONT_DIR = Path(__file__).resolve().parents[1] / "src/app/fonts"

# Shared punctuation stays with the preloaded Latin face. Combining marks are
# also retained in each script's file so decomposed accents can shape together.
LATIN = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,"
    "U+0300-036F,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,"
    "U+FEFF,U+FFFD"
)
SCRIPT_RANGES = {
    "latin-ext": "U+0100-036F,U+1D00-1EFF,U+2C60-2C7F,U+A720-A7FF,U+AB30-AB6F",
    "cyrillic": "U+0400-052F,U+1C80-1C8F,U+2DE0-2DFF,U+A640-A69F",
    "greek": "U+0370-03FF,U+1F00-1FFF",
}
MARKS = "U+0300-036F,U+1AB0-1AFF,U+1DC0-1DFF,U+20D0-20FF,U+FE20-FE2F"


def unicode_range(codepoints):
    """Compact the actual character map into CSS Unicode ranges."""
    ranges = []
    for codepoint in sorted(codepoints):
        if ranges and codepoint == ranges[-1][1] + 1:
            ranges[-1][1] = codepoint
        else:
            ranges.append([codepoint, codepoint])
    return ", ".join(
        f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}"
        for start, end in ranges
    )


def generate():
    output = FONT_DIR / "static/subsets"
    output.mkdir(exist_ok=True)
    css = ["/* Generated by web/scripts/subset-fonts.py. */\n"]
    for filename, style in [
        ("InterVariable.woff2", "normal"),
        ("InterVariable-Italic.woff2", "italic"),
    ]:
        source = FONT_DIR / "static" / filename
        with TTFont(source) as original:
            codepoints = set(original.getBestCmap())
        marks = codepoints & set(subset.parse_unicodes(MARKS))
        groups = {"latin": codepoints & set(subset.parse_unicodes(LATIN))}
        for name, ranges in SCRIPT_RANGES.items():
            groups[name] = (codepoints & set(subset.parse_unicodes(ranges))) - groups["latin"]
        groups["symbols"] = codepoints - set().union(*groups.values())

        for name, characters in groups.items():
            characters = characters | marks
            options = subset.Options()
            options.layout_features = ["*"]
            options.notdef_outline = True
            options.recalc_timestamp = False
            font = TTFont(source, recalcTimestamp=False)
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(unicodes=characters)
            subsetter.subset(font)
            font.flavor = "woff2"
            destination = output / f"{source.stem}-{name}.woff2"
            font.save(destination)
            font.close()
            print(f"{destination.name}: {destination.stat().st_size:,} bytes")
            if name == "latin":
                continue
            css.append(
                "@font-face {\n"
                '  font-family: "inter";\n'
                f'  src: url("./static/subsets/{destination.name}") format("woff2");\n'
                "  font-weight: 100 900;\n"
                f"  font-style: {style};\n"
                "  font-display: swap;\n"
                f"  unicode-range: {unicode_range(characters)};\n"
                "}\n"
            )
    (FONT_DIR / "subsets.css").write_text("\n".join(css))


if __name__ == "__main__":
    generate()
