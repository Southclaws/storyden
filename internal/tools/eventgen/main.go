const handlerTemplate = `// Code generated by eventgen. DO NOT EDIT.

package storyden

import (
	"context"

	"github.com/Southclaws/storyden/lib/plugin/rpc"
)

{{ range .Events }}
func (p *Plugin) On{{ .HandlerName }}(handler func(context.Context, *rpc.{{ .TypeName }}) error) {
	p.On("{{ .TypeName }}", func(ctx context.Context, event rpc.EventPayload) error {
		if e, ok := event.EventPayloadUnion.(*rpc.{{ .TypeName }}); ok {
			return handler(ctx, e)
		}
		return nil
	})
}
{{ end }}
`

const webEventNamesTemplate = `// Code generated by eventgen. DO NOT EDIT.

export const pluginEventNames = [
{{- range .Events }}
  {{ quote .TypeName }},
{{- end }}
] as const;

export type PluginEventName = (typeof pluginEventNames)[number];

export const events = [
{{- range .Events }}
  {
    name: {{ quote .TypeName }},
    label: {{ quote .Label }},
{{ webDescription .Description }}
  },
{{- end }}
] as const satisfies readonly {
  name: PluginEventName;
  label: string;
  description: string;
}[];
`

const eventDefinitionsTemplate = `// Code generated by eventgen. DO NOT EDIT.

package rpc

type EventFieldDefinition struct {
	Name        string
	Description string
	Required    bool
}

type EventDefinition struct {
	Name        Event
	Description string
	Fields      []EventFieldDefinition
}

var eventDefinitions = map[Event]EventDefinition{
{{- range .Events }}
	Event{{ .TypeName }}: {
		Name:        Event{{ .TypeName }},
		Description: {{ quote .Description }},
		Fields: []EventFieldDefinition{
{{- range .Fields }}
			{
				Name:        {{ quote .Name }},
				Description: {{ quote .Description }},
				Required:    {{ .Required }},
			},
{{- end }}
		},
	},
{{- end }}
}

func LookupEventDefinition(event Event) (EventDefinition, bool) {
	definition, ok := eventDefinitions[event]
	return definition, ok
}
`

const pythonEventNamesTemplate = `# Code generated by eventgen. DO NOT EDIT.

from typing import Literal, TypeAlias

plugin_event_names = [
{{- range .Events }}
    "{{ .TypeName }}",
{{- end }}
]

EventName: TypeAlias = Literal[
{{- range .Events }}
    "{{ .TypeName }}",
{{- end }}
]

__all__ = ["EventName", "plugin_event_names"]
`

type Event struct {
	TypeName    string
	HandlerName string
	Label       string
	Description string
	Fields      []EventField
}

type EventField struct {
	Name        string
	Description string
	Required    bool
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	schemaPath := filepath.Join("common", "events.yaml")
	goOutputPath := filepath.Join("..", "sdk", "go", "storyden", "handlers.go")
	eventDefinitionsOutputPath := filepath.Join("..", "lib", "plugin", "rpc", "event_definitions_gen.go")
	webOutputPath := filepath.Join("..", "web", "src", "api", "events.ts")
	pythonOutputPath := filepath.Join("..", "sdk", "python", "storyden", "rpc", "events.py")

	events, err := extractEventsFromSchema(schemaPath)
	if err != nil {
		return fmt.Errorf("failed to extract events: %w", err)
	}

	goCode, err := generateHandlers(events)
	if err != nil {
		return fmt.Errorf("failed to generate handlers: %w", err)
	}

	eventDefinitionsCode, err := generateEventDefinitions(events)
	if err != nil {
		return fmt.Errorf("failed to generate event definitions: %w", err)
	}

	webCode, err := generateWebEventNames(events)
	if err != nil {
		return fmt.Errorf("failed to generate web event names: %w", err)
	}

	pythonCode, err := generatePythonEventNames(events)
	if err != nil {
		return fmt.Errorf("failed to generate python event names: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(goOutputPath), 0o755); err != nil {
		return fmt.Errorf("failed to create Go output directory: %w", err)
	}

	if err := os.WriteFile(goOutputPath, goCode, 0o644); err != nil {
		return fmt.Errorf("failed to write Go output file: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(eventDefinitionsOutputPath), 0o755); err != nil {
		return fmt.Errorf("failed to create event definitions output directory: %w", err)
	}

	if err := os.WriteFile(eventDefinitionsOutputPath, eventDefinitionsCode, 0o644); err != nil {
		return fmt.Errorf("failed to write event definitions: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(webOutputPath), 0o755); err != nil {
		return fmt.Errorf("failed to create web output directory: %w", err)
	}

	if err := os.WriteFile(webOutputPath, webCode, 0o644); err != nil {
		return fmt.Errorf("failed to write web output file: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(pythonOutputPath), 0o755); err != nil {
		return fmt.Errorf("failed to create python output directory: %w", err)
	}

	if err := os.WriteFile(pythonOutputPath, pythonCode, 0o644); err != nil {
		return fmt.Errorf("failed to write Python output file: %w", err)
	}

	fmt.Printf("Generated %d event handlers in %s\n", len(events), goOutputPath)
	fmt.Printf("Generated %d event definitions in %s\n", len(events), eventDefinitionsOutputPath)
	fmt.Printf("Generated %d plugin event names in %s\n", len(events), webOutputPath)
	fmt.Printf("Generated %d plugin event names in %s\n", len(events), pythonOutputPath)
	return nil
}

func extractEventsFromSchema(schemaPath string) ([]Event, error) {
	yamlData, err := os.ReadFile(schemaPath)
	if err != nil {
		return nil, fmt.Errorf("failed to read schema file: %w", err)
	}

	var jsonData interface{}
	if err := yaml.Unmarshal(yamlData, &jsonData); err != nil {
		return nil, fmt.Errorf("failed to unmarshal YAML: %w", err)
	}

	jsonBytes, err := json.Marshal(jsonData)
	if err != nil {
		return nil, fmt.Errorf("failed to marshal to JSON: %w", err)
	}

	var schema jsonschema.Schema
	if err := json.Unmarshal(jsonBytes, &schema); err != nil {
		return nil, fmt.Errorf("failed to unmarshal JSON schema: %w", err)
	}

	eventPayloadDef, ok := schema.Defs["EventPayload"]
	if !ok {
		eventPayloadDef, ok = schema.Definitions["EventPayload"]
		if !ok {
			return nil, fmt.Errorf("EventPayload definition not found in schema (checked both $defs and definitions)")
		}
	}

	eventEnumDef, ok := schema.Defs["Event"]
	if !ok {
		eventEnumDef, ok = schema.Definitions["Event"]
		if !ok {
			return nil, fmt.Errorf("Event definition not found in schema (checked both $defs and definitions)")
		}
	}

	enumSet := make(map[string]bool, len(eventEnumDef.Enum))
	for _, v := range eventEnumDef.Enum {
		s, ok := v.(string)
		if !ok {
			continue
		}
		enumSet[s] = true
	}

	var events []Event
	var missing []string
	var missingDescriptions []string
	var missingFieldDescriptions []string

	for _, oneOfSchema := range eventPayloadDef.OneOf {
		if oneOfSchema.Ref == "" {
			continue
		}

		parts := strings.Split(oneOfSchema.Ref, "/")
		if len(parts) == 0 {
			continue
		}

		eventName := parts[len(parts)-1]
		if !strings.HasPrefix(eventName, "Event") {
			continue
		}

		if !enumSet[eventName] {
			missing = append(missing, eventName)
		}

		handlerName := strings.TrimPrefix(eventName, "Event")
		eventSchema, ok := schema.Defs[eventName]
		if !ok {
			eventSchema, ok = schema.Definitions[eventName]
		}
		description := ""
		if ok {
			description = strings.TrimSpace(eventSchema.Description)
		}
		if description == "" {
			missingDescriptions = append(missingDescriptions, eventName)
		}

		fields := extractEventFields(eventSchema)
		for _, field := range fields {
			if field.Description == "" {
				missingFieldDescriptions = append(missingFieldDescriptions, eventName+"."+field.Name)
			}
		}

		events = append(events, Event{
			TypeName:    eventName,
			HandlerName: handlerName,
			Label:       eventLabel(eventName),
			Description: description,
			Fields:      fields,
		})
	}

	if len(missing) > 0 {
		return nil, fmt.Errorf("events defined in EventPayload but missing from Event enum: %s", strings.Join(missing, ", "))
	}
	if len(missingDescriptions) > 0 {
		return nil, fmt.Errorf("events missing descriptions: %s", strings.Join(missingDescriptions, ", "))
	}
	if len(missingFieldDescriptions) > 0 {
		return nil, fmt.Errorf("event fields missing descriptions: %s", strings.Join(missingFieldDescriptions, ", "))
	}

	payloadSet := make(map[string]bool, len(events))
	for _, e := range events {
		payloadSet[e.TypeName] = true
	}

	var extra []string
	for name := range enumSet {
		if !payloadSet[name] {
			extra = append(extra, name)
		}
	}

	if len(extra) > 0 {
		return nil, fmt.Errorf("events defined in Event enum but missing from EventPayload: %s", strings.Join(extra, ", "))
	}

	return events, nil
}

func extractEventFields(schema *jsonschema.Schema) []EventField {
	if schema == nil {
		return nil
	}

	required := make(map[string]struct{}, len(schema.Required))
	var names []string
	for _, name := range schema.Required {
		required[name] = struct{}{}
		if name != "event" {
			names = append(names, name)
		}
	}
	var optional []string
	for name := range schema.Properties {
		if name == "event" {
			continue
		}
		if _, ok := required[name]; !ok {
			optional = append(optional, name)
		}
	}
	sort.Strings(optional)
	names = append(names, optional...)

	fields := make([]EventField, 0, len(names))
	for _, name := range names {
		property := schema.Properties[name]
		description := ""
		if property != nil {
			description = strings.TrimSpace(property.Description)
		}
		_, isRequired := required[name]
		fields = append(fields, EventField{
			Name:        name,
			Description: description,
			Required:    isRequired,
		})
	}

	return fields
}

func eventLabel(typeName string) string {
	name := strings.TrimPrefix(typeName, "Event")
	var words strings.Builder

	for index, character := range name {
		if index > 0 && unicode.IsUpper(character) {
			words.WriteByte(' ')
		}
		words.WriteRune(unicode.ToLower(character))
	}

	label := words.String()
	if label == "" {
		return typeName
	}

	first, size := utf8.DecodeRuneInString(label)
	return string(unicode.ToUpper(first)) + label[size:]
}

func generateHandlers(events []Event) ([]byte, error) {
	tmpl, err := template.New("handlers").Parse(handlerTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]interface{}{
		"Events": events,
	}); err != nil {
		return nil, fmt.Errorf("failed to execute template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format code: %w", err)
	}

	return formatted, nil
}

func generateEventDefinitions(events []Event) ([]byte, error) {
	tmpl, err := template.New("event-definitions").Funcs(template.FuncMap{
		"quote": strconv.Quote,
	}).Parse(eventDefinitionsTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]interface{}{
		"Events": events,
	}); err != nil {
		return nil, fmt.Errorf("failed to execute template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format code: %w", err)
	}

	return formatted, nil
}

func generateWebEventNames(events []Event) ([]byte, error) {
	tmpl, err := template.New("web-events").Funcs(template.FuncMap{
		"quote":          strconv.Quote,
		"webDescription": formatWebDescription,
	}).Parse(webEventNamesTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]interface{}{
		"Events": events,
	}); err != nil {
		return nil, fmt.Errorf("failed to execute template: %w", err)
	}

	return buf.Bytes(), nil
}

func formatWebDescription(description string) string {
	literal := strconv.Quote(description)
	line := "    description: " + literal + ","
	if len(line) <= 80 {
		return line
	}

	return "    description:\n      " + literal + ","
}

func generatePythonEventNames(events []Event) ([]byte, error) {
	tmpl, err := template.New("python-events").Parse(pythonEventNamesTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]interface{}{
		"Events": events,
	}); err != nil {
		return nil, fmt.Errorf("failed to execute template: %w", err)
	}

	return buf.Bytes(), nil
}
